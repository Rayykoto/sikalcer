export function downloadSampleGpx(preset: "run" | "ride"): void {
  const content = preset === "run" ? LARI_SUDIRMAN_GPX : SEPEDA_SENTUL_GPX;
  const filename =
    preset === "run"
      ? "test-lari-sudirman-monas.gpx"
      : "test-sepeda-sentul-km0.gpx";

  const blob = new Blob([content], { type: "application/gpx+xml;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  link.click();
  URL.revokeObjectURL(url);
}